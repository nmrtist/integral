//! Independent cross-check of the `c2s` coefficient matrix against a
//! high-precision (50-digit) **mpmath** reference.
//!
//! The Rust production path ([`c2s_matrix`]) builds the transform from an
//! explicit binomial closed form (Schlegel–Frisch / Racah real solid harmonics).
//! The reference below is derived by a *different* route — numerically projecting
//! `mpmath.spherharm` onto the Cartesian monomial basis at 50 digits, then
//! unit-normalizing against the raw (solid-harmonic) Gaussian self-overlap. Because the
//! two share only the *definition* of the quantity, agreement validates both and
//! catches a transcription error in the closed form that orthonormality alone
//! could not (orthonormality is invariant under relabeling the `(2l+1)` rows).
//!
//! Rows are compared **up to an overall sign** (each row sign-fixed so its first
//! nonzero entry is positive); the exact Condon–Shortley sign and the m-ordering
//! are pinned separately by the signed reference in
//! `c2s_independent_reference.rs`.

// The reference table below is machine-generated at 17 significant figures;
// digit separators would be noise and the trailing digits (beyond f64's ~16) are
// intentional so the literal rounds to the nearest representable value.
#![allow(clippy::unreadable_literal, clippy::excessive_precision)]

use integral::math::am::n_cart;
use integral::math::solid_harmonics::c2s_matrix;

/// Sign-fix a row in place: negate it so its first significant entry is positive.
fn sign_fix(row: &mut [f64]) {
    for &v in row.iter() {
        if v.abs() > 1e-12 {
            if v < 0.0 {
                for x in row.iter_mut() {
                    *x = -*x;
                }
            }
            break;
        }
    }
}

#[test]
fn c2s_matches_mpmath_reference() {
    let mut ref_rows = C2S_REF.iter();
    for l in 0..=6 {
        let mat = c2s_matrix(l);
        let nc = n_cart(l);
        for p in 0..(2 * l + 1) {
            let mut row: Vec<f64> = mat[p * nc..(p + 1) * nc].to_vec();
            sign_fix(&mut row);
            let refr = ref_rows.next().expect("missing reference row");
            assert_eq!(refr.len(), nc, "l={l} row={p}: width mismatch");
            for (i, (&a, &b)) in row.iter().zip(refr.iter()).enumerate() {
                assert!(
                    (a - b).abs() < 1e-12,
                    "l={l} row={p} col={i}: rust={a} mpmath={b} (Δ={:e})",
                    (a - b).abs()
                );
            }
        }
    }
    assert!(
        ref_rows.next().is_none(),
        "reference has more rows than c2s produced"
    );
}

