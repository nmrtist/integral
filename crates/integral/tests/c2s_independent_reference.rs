//! Independent SIGNED cross-check of `c2s_matrix`.
//!
//! Unlike `tests/c2s_reference.rs` (which sign-fixes each row and therefore pins
//! coefficients only *up to an arbitrary per-row sign*), this reference carries a
//! DEFINITE sign per (l, m), derived through a genuinely different route: the
//! complex `mpmath.spherharm` combined via the standard Blanco-Florez-Bermejo
//! (1997) complex->real unitary transform (which removes the Condon-Shortley
//! phase), projected onto Cartesian monomials at 60 digits, then unit-normalized
//! against the raw Gaussian self-overlap WITHOUT any sign-fix.
//!
//! Asserting `c2s_matrix(l)` equals this table element-by-element INCLUDING SIGN
//! establishes that the implementation's coefficient signs are fixed by the
//! literature real-solid-harmonic convention — not "fitted" to a reference. (The
//! m-ordering used here is the implementation's claimed order; for l != 1 that is
//! the literature-standard ascending m, the l == 1 (px,py,pz) reorder being the
//! only convention-specific reordering.)

#![allow(clippy::unreadable_literal, clippy::excessive_precision)]

use integral::math::am::n_cart;
use integral::math::solid_harmonics::c2s_matrix;

#[test]
fn c2s_matches_independent_signed_reference() {
    let mut ref_rows = C2S_SIGNED_REF.iter();
    let mut worst = 0.0_f64;
    for l in 0..=6 {
        let mat = c2s_matrix(l);
        let nc = n_cart(l);
        for p in 0..(2 * l + 1) {
            let row = &mat[p * nc..(p + 1) * nc];
            let refr = ref_rows.next().expect("missing reference row");
            assert_eq!(refr.len(), nc, "l={l} row={p}: width mismatch");
            for (i, (&a, &b)) in row.iter().zip(refr.iter()).enumerate() {
                let d = (a - b).abs();
                worst = worst.max(d);
                assert!(
                    d < 1e-12,
                    "l={l} row={p} col={i}: rust={a} signed_ref={b} (Δ={d:e}) \
                     — SIGN OR VALUE MISMATCH"
                );
            }
        }
    }
    assert!(ref_rows.next().is_none(), "reference has extra rows");
    eprintln!("c2s vs independent signed reference: worst |Δ| = {worst:e}");
}

